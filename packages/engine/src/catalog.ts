/**
 * Catálogo central de métricas: UNA fuente para el motor, la API y el futuro frontend.
 * Distingue siempre: recuperado de código (R) · documentado por la aplicación (D) · aproximación experimental (A) ·
 * regla operativa propuesta (P) · desconocido (U). Nada propuesto o aproximado se presenta como fórmula exacta.
 */
export type Provenance = 'recuperado' | 'documentado' | 'aproximado' | 'propuesta' | 'desconocido';
export type Implementation = 'implementada' | 'catalogada_sin_calculo' | 'disputada_no_implementada';

export interface MetricDefinition {
  id: string;
  name: string;
  definition: string;
  unit: string;
  method: string;
  version: string;
  provenance: Provenance;
  reference: string;
  inputs: string[];
  domain: string;
  exclusions: string[];
  /** Niveles de agregación permitidos. */
  aggregation: string[];
  interpretation: { up: string | null; down: string | null };
  doesNotConclude: string[];
  limitations: string[];
  implementation: Implementation;
  /** Familia de modelo: valores de familias distintas NO se suman ni se comparan como si compartieran escala. */
  modelFamily: string | null;
}

